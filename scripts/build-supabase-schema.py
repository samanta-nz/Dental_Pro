#!/usr/bin/env python3
"""Regenerate a single schema bootstrap without publishing historical/dummy app releases."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
migrations = sorted((root / 'supabase/migrations').glob('*.sql'))
# 0006 is a historical release announcement, not part of the database schema.
selected = [p for p in migrations if not p.name.startswith('0006_')]
output = ['-- Generated by scripts/build-supabase-schema.py. Back up existing data before applying.',
          '-- Creates/upgrades schema; does not publish an APK or create example release announcements.', 'begin;']
for path in selected:
    content = path.read_text()
    # Historical local-ID uniqueness is replaced by the stable source identity in 0016.
    content = re.sub(r"create unique index if not exists idx_financial_ledger_source[^;]*;", "", content, flags=re.I)
    output.extend([f'\n-- Source: {path.name}', content])
output.append('commit;\n')
(root / 'supabase/dentalpro_all_in_one.sql').write_text('\n'.join(output))
print(f'Generated schema from {len(selected)} migrations.')
